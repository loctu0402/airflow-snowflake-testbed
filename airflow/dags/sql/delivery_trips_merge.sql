MERGE INTO DELIVERY.TRIPS AS TGT
USING (
    SELECT
        TRIP_ID,
        ORDER_ID,
        COURIER_ID,
        PICKED_UP_AT,
        DELIVERED_AT,
        DISTANCE_KM
    FROM DELIVERY.TRIPS_LANDING
    QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIP_ID ORDER BY DELIVERED_AT DESC NULLS LAST) = 1
) AS SRC
    ON TGT.TRIP_ID = SRC.TRIP_ID
WHEN MATCHED THEN
    UPDATE SET
        TGT.ORDER_ID = SRC.ORDER_ID,
        TGT.COURIER_ID = SRC.COURIER_ID,
        TGT.PICKED_UP_AT = SRC.PICKED_UP_AT,
        TGT.DELIVERED_AT = SRC.DELIVERED_AT,
        TGT.DISTANCE_KM = SRC.DISTANCE_KM,
        TGT.LOADED_AT = SYSDATE()
WHEN NOT MATCHED THEN INSERT (
    TRIP_ID, ORDER_ID, COURIER_ID, PICKED_UP_AT, DELIVERED_AT, DISTANCE_KM, LOADED_AT
) VALUES (
    SRC.TRIP_ID, SRC.ORDER_ID, SRC.COURIER_ID, SRC.PICKED_UP_AT, SRC.DELIVERED_AT, SRC.DISTANCE_KM, SYSDATE()
);
