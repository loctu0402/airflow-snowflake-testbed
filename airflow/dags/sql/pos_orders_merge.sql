MERGE INTO POS.ORDERS AS TGT
USING (
    SELECT
        ORDER_ID,
        STORE_ID,
        ORDERED_AT,
        STATUS,
        TOTAL_AMOUNT,
        UPDATED_AT
    FROM POS.ORDERS_LANDING
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY UPDATED_AT DESC) = 1
) AS SRC
    ON TGT.ORDER_ID = SRC.ORDER_ID
WHEN MATCHED AND SRC.UPDATED_AT >= TGT.UPDATED_AT THEN
    UPDATE SET
        TGT.STORE_ID = SRC.STORE_ID,
        TGT.ORDERED_AT = SRC.ORDERED_AT,
        TGT.STATUS = SRC.STATUS,
        TGT.TOTAL_AMOUNT = SRC.TOTAL_AMOUNT,
        TGT.UPDATED_AT = SRC.UPDATED_AT,
        TGT.LOADED_AT = SYSDATE()
WHEN NOT MATCHED THEN INSERT (
    ORDER_ID, STORE_ID, ORDERED_AT, STATUS, TOTAL_AMOUNT, UPDATED_AT, LOADED_AT
) VALUES (
    SRC.ORDER_ID, SRC.STORE_ID, SRC.ORDERED_AT, SRC.STATUS, SRC.TOTAL_AMOUNT, SRC.UPDATED_AT, SYSDATE()
);
