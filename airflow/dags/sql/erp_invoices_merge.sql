MERGE INTO ERP.INVOICES AS TGT
USING (
    SELECT
        INVOICE_ID,
        SUPPLIER_ID,
        INVOICE_DATE,
        AMOUNT,
        CURRENCY,
        UPDATED_AT
    FROM ERP.INVOICES_LANDING
    QUALIFY ROW_NUMBER() OVER (PARTITION BY INVOICE_ID ORDER BY UPDATED_AT DESC) = 1
) AS SRC
    ON TGT.INVOICE_ID = SRC.INVOICE_ID
WHEN MATCHED AND SRC.UPDATED_AT >= TGT.UPDATED_AT THEN
    UPDATE SET
        TGT.SUPPLIER_ID = SRC.SUPPLIER_ID,
        TGT.INVOICE_DATE = SRC.INVOICE_DATE,
        TGT.AMOUNT = SRC.AMOUNT,
        TGT.CURRENCY = SRC.CURRENCY,
        TGT.UPDATED_AT = SRC.UPDATED_AT,
        TGT.LOADED_AT = SYSDATE()
WHEN NOT MATCHED THEN INSERT (
    INVOICE_ID, SUPPLIER_ID, INVOICE_DATE, AMOUNT, CURRENCY, UPDATED_AT, LOADED_AT
) VALUES (
    SRC.INVOICE_ID, SRC.SUPPLIER_ID, SRC.INVOICE_DATE, SRC.AMOUNT, SRC.CURRENCY, SRC.UPDATED_AT, SYSDATE()
);
