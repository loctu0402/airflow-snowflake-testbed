USE ROLE SYSADMIN;

CREATE OR REPLACE PROCEDURE OPS.TESTBED.REFRESH_TEST()
RETURNS VARCHAR
LANGUAGE PYTHON
RUNTIME_VERSION = '3.11'
PACKAGES = ('snowflake-snowpark-python')
HANDLER = 'run'
EXECUTE AS OWNER
AS
$$
STATEMENTS = (
    "CREATE OR REPLACE DATABASE DW_TEST CLONE DW_PROD",
    "GRANT USAGE ON DATABASE DW_TEST TO ROLE TESTER",
    "GRANT USAGE ON ALL SCHEMAS IN DATABASE DW_TEST TO ROLE TESTER",
    "GRANT SELECT ON ALL TABLES IN DATABASE DW_TEST TO ROLE TESTER",
    "GRANT SELECT ON ALL VIEWS IN DATABASE DW_TEST TO ROLE TESTER",
)


def run(session):
    for statement in STATEMENTS:
        session.sql(statement).collect()
    return "DW_TEST cloned from DW_PROD"
$$;

CREATE OR REPLACE TASK OPS.TESTBED.REFRESH_TEST_NIGHTLY
    WAREHOUSE = TEST_WH
    SCHEDULE = 'USING CRON 0 4 * * * UTC'
AS
    CALL OPS.TESTBED.REFRESH_TEST();

ALTER TASK OPS.TESTBED.REFRESH_TEST_NIGHTLY RESUME;

CALL OPS.TESTBED.REFRESH_TEST();
