USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS DELIVERY_EXPORTS
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = 'S3'
ENABLED = TRUE
STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::123456789012:role/snowflake-delivery-exports'
STORAGE_ALLOWED_LOCATIONS = ('s3://example-delivery-exports/trips/');

GRANT USAGE ON INTEGRATION DELIVERY_EXPORTS TO ROLE LOADER;

USE ROLE LOADER;
USE WAREHOUSE LOAD_WH;
USE DATABASE DW_PROD;

CREATE TRANSIENT TABLE IF NOT EXISTS POS.ORDERS_LANDING (
    ORDER_ID VARCHAR NOT NULL,
    STORE_ID VARCHAR NOT NULL,
    ORDERED_AT TIMESTAMP_NTZ NOT NULL,
    STATUS VARCHAR,
    TOTAL_AMOUNT NUMBER(12, 2),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS POS.ORDERS (
    ORDER_ID VARCHAR NOT NULL,
    STORE_ID VARCHAR NOT NULL,
    ORDERED_AT TIMESTAMP_NTZ NOT NULL,
    STATUS VARCHAR,
    TOTAL_AMOUNT NUMBER(12, 2),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL,
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TRANSIENT TABLE IF NOT EXISTS ERP.INVOICES_LANDING (
    INVOICE_ID VARCHAR NOT NULL,
    SUPPLIER_ID VARCHAR NOT NULL,
    INVOICE_DATE DATE NOT NULL,
    AMOUNT NUMBER(14, 2),
    CURRENCY VARCHAR(3),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ERP.INVOICES (
    INVOICE_ID VARCHAR NOT NULL,
    SUPPLIER_ID VARCHAR NOT NULL,
    INVOICE_DATE DATE NOT NULL,
    AMOUNT NUMBER(14, 2),
    CURRENCY VARCHAR(3),
    UPDATED_AT TIMESTAMP_NTZ NOT NULL,
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE FILE FORMAT IF NOT EXISTS DELIVERY.CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE STAGE IF NOT EXISTS DELIVERY.TRIPS_STAGE
    URL = 's3://example-delivery-exports/trips/'
    STORAGE_INTEGRATION = DELIVERY_EXPORTS
    FILE_FORMAT = DELIVERY.CSV_FORMAT;

CREATE TRANSIENT TABLE IF NOT EXISTS DELIVERY.TRIPS_LANDING (
    TRIP_ID VARCHAR NOT NULL,
    ORDER_ID VARCHAR NOT NULL,
    COURIER_ID VARCHAR,
    PICKED_UP_AT TIMESTAMP_NTZ,
    DELIVERED_AT TIMESTAMP_NTZ,
    DISTANCE_KM NUMBER(8, 2)
);

CREATE TABLE IF NOT EXISTS DELIVERY.TRIPS (
    TRIP_ID VARCHAR NOT NULL,
    ORDER_ID VARCHAR NOT NULL,
    COURIER_ID VARCHAR,
    PICKED_UP_AT TIMESTAMP_NTZ,
    DELIVERED_AT TIMESTAMP_NTZ,
    DISTANCE_KM NUMBER(8, 2),
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);
