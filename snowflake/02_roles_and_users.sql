USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS REPORTER;
CREATE ROLE IF NOT EXISTS TESTER;

GRANT ROLE LOADER TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER TO ROLE SYSADMIN;
GRANT ROLE TESTER TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS SVC_AIRFLOW
    TYPE = SERVICE
    DEFAULT_ROLE = LOADER
    DEFAULT_WAREHOUSE = LOAD_WH;

CREATE USER IF NOT EXISTS SVC_AIRFLOW_TEST
    TYPE = SERVICE
    DEFAULT_ROLE = TESTER
    DEFAULT_WAREHOUSE = TEST_WH;

GRANT ROLE LOADER TO USER SVC_AIRFLOW;
GRANT ROLE TESTER TO USER SVC_AIRFLOW_TEST;
